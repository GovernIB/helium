-- #2018 Flowable: finalització de tasques en segon pla i esperes de portasignatures/PINBAL

-- Finalització de tasques en segon pla (amb jBPM eren columnes de JBPM_TASKINSTANCE)
ALTER TABLE HEL_TASCA_EXPEDIENT ADD (
	MARCADA_FINALITZAR	TIMESTAMP(6),
	INICI_FINALITZACIO	TIMESTAMP(6),
	ERROR_FINALITZACIO	VARCHAR2(1000 CHAR),
	SELECTED_OUTCOME	VARCHAR2(255 CHAR),
	ROLS				VARCHAR2(2000 CHAR)
);

-- L'execució que espera la resposta del portasignatures o de PINBAL és un id de Flowable (UUID), no un número.
-- Oracle no permet canviar el tipus d'una columna amb dades: es crea una columna nova i es copien els valors.
ALTER TABLE HEL_PORTASIGNATURES ADD (TOKEN_ID_NOU VARCHAR2(64 CHAR));
UPDATE HEL_PORTASIGNATURES SET TOKEN_ID_NOU = TO_CHAR(TOKEN_ID);
-- TOKEN_ID forma part de la restricció única (DOCUMENT_ID, TOKEN_ID)
ALTER TABLE HEL_PORTASIGNATURES DROP COLUMN TOKEN_ID CASCADE CONSTRAINTS;
ALTER TABLE HEL_PORTASIGNATURES RENAME COLUMN TOKEN_ID_NOU TO TOKEN_ID;
ALTER TABLE HEL_PORTASIGNATURES ADD UNIQUE (DOCUMENT_ID, TOKEN_ID);

ALTER TABLE HEL_PETICIO_PINBAL ADD (TOKEN_ID_NOU VARCHAR2(64 CHAR));
UPDATE HEL_PETICIO_PINBAL SET TOKEN_ID_NOU = TO_CHAR(TOKEN_ID);
ALTER TABLE HEL_PETICIO_PINBAL DROP COLUMN TOKEN_ID;
ALTER TABLE HEL_PETICIO_PINBAL RENAME COLUMN TOKEN_ID_NOU TO TOKEN_ID;
